"""Activity model."""

from datetime import datetime
from typing import Annotated

from pydantic import MISSING, Field

from entitysdk.models.core import Identifiable
from entitysdk.models.entity import Entity
from entitysdk.types import ID, ActivityStatus, ActivityType


class Activity(Identifiable):
    """Activity model."""

    # Server-assigned from the activity route / SQLAlchemy polymorphic identity.
    # Not on ActivityCreate; clients must not send it (excluded in serdes).
    type: Annotated[
        ActivityType,
        Field(description="The type of the activity (server-assigned)."),
    ] = MISSING  # type: ignore[assignment]

    authorized_public: Annotated[
        bool,
        Field(
            description="Whether the resource is authorized to be public.",
        ),
    ] = False
    # Server-assigned from project context headers; not on ActivityCreate (excluded in serdes).
    authorized_project_id: Annotated[
        ID,
        Field(description="The project ID owning the resource (server-assigned)."),
    ] = MISSING  # type: ignore[assignment]

    status: Annotated[
        ActivityStatus,
        Field(description="The status of the activity."),
    ] = ActivityStatus.done
    # entitycore ActivityCreate: start_time/end_time are optional nullable.
    start_time: Annotated[
        datetime | None,
        Field(description="The time at which the activity started."),
    ] = MISSING  # type: ignore[assignment]
    end_time: Annotated[
        datetime | None,
        Field(description="The time at which the activity ended."),
    ] = MISSING  # type: ignore[assignment]

    used: Annotated[
        list[Entity],
        Field(description="Entities that were used by this activity."),
    ] = MISSING  # type: ignore[assignment]
    generated: Annotated[
        list[Entity],
        Field(description="Entities that were generated by this activity."),
    ] = MISSING  # type: ignore[assignment]
